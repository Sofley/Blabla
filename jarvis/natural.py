def clean(text):
    t = C.norm(text)
    for f in sorted(FILLERS, key=len, reverse=True):
        t = re.sub(rf"(^|\s){re.escape(f)}(?=\s|$)", " ", t)
    t = re.sub(r"\s+", " ", t).strip()
    for base, forms in VERBS.items():
        for f in sorted(forms, key=len, reverse=True):
            t = re.sub(rf"(^|\s){re.escape(f)}(?=\s|$)", rf"\1{base}", t)
    # «включи музыку X» / «поставь песню X» -> ютуб
    m = re.match(r"^(включи|поставь|запусти|открой) (музыку|песню|песни|трек|видео|клип|фильм|мультик|мультфильм)( .+)?$", t)
    if m:
        what = (m.group(3) or "").strip()
        if m.group(2) == "музыку":
            what = ("музыка " + what).strip()
        return f"найди на ютубе {what or m.group(2)}"
    return re.sub(r"\s+", " ", t).strip()


def has(root, text):
    """Корень из нескольких слов совпадает, если все его части есть во фразе (в любом месте)."""
    parts = root.split()
    if len(parts) == 1:
        return root in text
    words = text.split()
    return all(any(w.startswith(p) or p in w for w in words) for p in parts)


TG_SEND = re.compile(r"^(напиши|отправь|скажи|передай|сообщи) (\S+) (что |чтобы |мол )?(.+)$")


def scene_of(t):
    for scene, roots in SCENE_WORDS.items():
        if any(r in t for r in roots):
            if any(v in t for v in SCENE_VERBS) or len(t.split()) <= 2:
                return scene
    return None


def understand(text, ai_available=False):
    """Возвращает (команда или None, очищенная фраза). None — пусть думает ИИ (или «не понял»)."""
    raw = C.norm(text)
    t = clean(text)
    if not t:
        return None, t
    # переключение сцены — словами, как человеку удобно
    sc = scene_of(raw)
    if sc:
        return {"intent": "scene", "name": sc}, t
    cmd = C.parse(t) or C.parse(raw)
    if cmd:
        return cmd, t
    m = TG_SEND.match(t)
    if m and m.group(2) not in ("текст", "в", "на", "мне", "это"):
        return {"intent": "tg_send", "contact": m.group(2), "text": m.group(4)}, t
    for roots, intent in KEYWORDS:
        if any(has(r, raw) or has(r, t) for r in roots):
            return dict(intent), t
    best, score = None, 0.0
    for phrase, intent in EXAMPLES.items():
        s = difflib.SequenceMatcher(None, t, phrase).ratio()
        if s > score:
            best, score = intent, s
    if best and score >= .72:
        return dict(best), t
    if ai_available:
        return None, t
    # без ИИ: вопрос — ищем ответ в интернете, а не говорим «не понял»
    if raw.startswith(QUESTION_START) or raw.endswith(("ли", "это")) or len(raw.split()) >= 4:
        return {"intent": "search", "query": raw, "fallback": True}, t
    return None, t


